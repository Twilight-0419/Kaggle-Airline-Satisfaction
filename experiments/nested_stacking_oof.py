"""Strict outer-CV stacking using existing XGBoost, LightGBM and CatBoost models.

Each outer validation fold is excluded from every first-layer fit. Within each
outer-training partition, first-layer training features are generated by an inner
OOF split (fixed-round models, no early stopping on the OOF holdout). A Logistic
Regression meta-model sees only those inner-OOF predictions.
"""
from __future__ import annotations

import gc
import json
import time
from itertools import combinations
from pathlib import Path

import catboost as cb
import lightgbm as lgb
import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold, train_test_split

from feature_screen import feature_configs

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "outputs" / "nested_stacking"
STACK = ROOT / "outputs" / "public_stack"
PUBLIC = next(ROOT.glob("某个公开算法*")) / "extra_oof" / "s6e10-oof"
TARGET, ID = "satisfaction", "id"
MODELS = ["xgboost", "lightgbm", "catboost"]
N_SAMPLE = 280_000  # same cohort used by existing outputs/ensemble OOF files
SAMPLE_SEED = 42
OUTER_FOLDS = 5
OUTER_SEED = 42
INNER_FOLDS = 5
INNER_SEED_BASE = 31415
MODEL_SEED = 42
N_ESTIMATORS = 300  # fixed rounds avoid using an OOF holdout for early stopping
GRID_STEP = 0.1
LR_C = 1.0


def simplex_grid(n: int, step: float):
    units = round(1 / step)
    if not np.isclose(units * step, 1.0):
        raise ValueError("Grid step must divide one")
    def rec(left, k, prefix=()):
        if k == 1:
            yield np.asarray(prefix + (left,), dtype=np.float64) / units
            return
        for v in range(left + 1):
            yield from rec(left - v, k - 1, prefix + (v,))
    return list(rec(units, n))


def fit_base(model_name, X, y, sample_weight=None):
    if model_name == "xgboost":
        model = xgb.XGBClassifier(
            objective="binary:logistic", eval_metric="auc", n_estimators=N_ESTIMATORS,
            learning_rate=0.05, max_depth=7, min_child_weight=10,
            subsample=0.85, colsample_bytree=0.7, reg_lambda=2.0,
            tree_method="hist", device="cpu", n_jobs=8, random_state=MODEL_SEED,
        )
    elif model_name == "lightgbm":
        model = lgb.LGBMClassifier(
            objective="binary", metric="auc", n_estimators=N_ESTIMATORS,
            learning_rate=0.03, num_leaves=63, min_child_samples=20,
            subsample=0.85, subsample_freq=1, colsample_bytree=0.7,
            reg_lambda=2.0, n_jobs=8, random_state=MODEL_SEED, verbosity=-1,
        )
    elif model_name == "catboost":
        model = cb.CatBoostClassifier(
            iterations=N_ESTIMATORS, learning_rate=0.03, depth=7,
            l2_leaf_reg=3.0, loss_function="Logloss", eval_metric="AUC",
            random_seed=MODEL_SEED, thread_count=8, verbose=False,
            allow_writing_files=False,
        )
    else:
        raise ValueError(model_name)
    if model_name == "xgboost":
        model.fit(X, y, sample_weight=sample_weight, verbose=False)
    else:
        model.fit(X, y, sample_weight=sample_weight)
    return model


def load_current_best_oof(sample_ids, full_train_ids):
    positions = pd.Index(full_train_ids.to_numpy()).get_indexer(sample_ids.to_numpy())
    if (positions < 0).any():
        raise ValueError("Sample IDs missing in full-train OOF arrays")
    weights = pd.read_csv(STACK / "fine_triple_cv.csv").iloc[0]
    p0 = np.load(STACK / "ext_l2_oof.npy")[positions]
    p1 = np.load(STACK / "xgboost_meta_tuned_oof.npy")[positions]
    df = pd.read_csv(PUBLIC / "05_blend_oof.csv", usecols=[ID, TARGET])
    if not df[ID].is_unique:
        raise ValueError("Duplicate public OOF IDs")
    idx = pd.Index(df[ID].to_numpy()).get_indexer(sample_ids.to_numpy())
    if (idx < 0).any():
        raise ValueError("Sample IDs missing from Najiama 05 OOF")
    p2 = df[TARGET].to_numpy(dtype=np.float64)[idx]
    current = float(weights["w_ext_l2"]) * p0 + float(weights["w_xgb_meta"]) * p1 + float(weights["w_najiama05"]) * p2
    if not np.isfinite(current).all():
        raise ValueError("Current-best OOF predictions contain non-finite values")
    return current


def save_existing_complementarity(sample_ids, y):
    ensemble = ROOT / "outputs" / "ensemble"
    preds = {}
    for name in MODELS:
        f = pd.read_csv(ensemble / f"{name}_oof.csv", usecols=[ID, TARGET])
        if not f[ID].is_unique:
            raise ValueError(f"{name} OOF has duplicate IDs")
        ix = pd.Index(f[ID].to_numpy()).get_indexer(sample_ids.to_numpy())
        if (ix < 0).any():
            raise ValueError(f"{name} OOF does not cover the selected cohort")
        preds[name] = f[TARGET].to_numpy(dtype=np.float64)[ix]
    rows = []
    for name, p in preds.items():
        rows.append({"type": "single", "model_a": name, "model_b": "", "oof_auc": roc_auc_score(y, p), "pearson_correlation": np.nan})
    for a, b in combinations(MODELS, 2):
        rows.append({"type": "equal_pair", "model_a": a, "model_b": b,
                     "oof_auc": roc_auc_score(y, (preds[a] + preds[b]) / 2),
                     "pearson_correlation": np.corrcoef(preds[a], preds[b])[0, 1]})
    rows.append({"type": "equal_all_three", "model_a": "+".join(MODELS), "model_b": "",
                 "oof_auc": roc_auc_score(y, np.column_stack([preds[m] for m in MODELS]).mean(axis=1)),
                 "pearson_correlation": np.nan})
    pd.DataFrame(rows).to_csv(OUT / "existing_base_oof_complementarity.csv", index=False)


def main():
    started_all = time.perf_counter()
    OUT.mkdir(parents=True, exist_ok=True)
    # Read train only. No test file or test labels are touched in this experiment.
    all_train = pd.read_csv(DATA / "train.csv")
    if not all_train[ID].is_unique or all_train[TARGET].isna().any():
        raise ValueError("Invalid train IDs or labels")
    sample, _ = train_test_split(
        all_train, train_size=N_SAMPLE, stratify=all_train[TARGET], random_state=SAMPLE_SEED
    )
    sample = sample.reset_index(drop=True)
    y = sample[TARGET].astype(np.int8).to_numpy()
    sample_ids = sample[ID].reset_index(drop=True)
    current_best = load_current_best_oof(sample_ids, all_train[ID])
    save_existing_complementarity(sample_ids, y)

    feature_names, categorical = feature_configs()["raw"]
    raw = sample[feature_names].copy().reset_index(drop=True)
    config = {
        "cohort_rows": N_SAMPLE,
        "cohort_selection": "train_test_split(train_size=280000, stratify=y, random_state=42), matching outputs/ensemble OOF cohort",
        "outer_cv": {"n_splits": OUTER_FOLDS, "shuffle": True, "random_state": OUTER_SEED},
        "inner_cv": {"n_splits": INNER_FOLDS, "shuffle": True, "random_state_per_outer_fold": "31415 + outer_fold_number"},
        "first_layer_models": MODELS,
        "raw_features": feature_names,
        "categorical_columns": categorical,
        "fixed_rounds_no_early_stopping": N_ESTIMATORS,
        "model_seed": MODEL_SEED,
        "level2": {"model": "LogisticRegression", "C": LR_C, "features": "three inner-OOF first-layer probabilities"},
        "simple_fusion_inner_train_weight_grid_step": GRID_STEP,
        "leakage_controls": [
            "Outer validation indices never enter any first-layer fit; all inner-fit indices are subsets of outer-training indices.",
            "Each outer-training row receives first-layer predictions from an inner model that did not train on that row.",
            "Fixed boosting rounds; no early stopping or model selection reads inner/outer validation labels.",
            "Second-layer LogisticRegression is fitted only on inner-OOF predictions from outer-training rows.",
            "Outer validation rows are scored once after first-layer fold models and second-layer fit are complete.",
            "No test data or test labels are used.",
        ],
        "comparison_note": "Current-best OOF reference is included for requested comparison; the nested XGB/LGB/CatBoost stack and its simple-fusion controls are the strict outer-CV estimates.",
    }
    (OUT / "experiment_config.json").write_text(json.dumps(config, indent=2, ensure_ascii=False), encoding="utf-8")

    outer_cv = StratifiedKFold(OUTER_FOLDS, shuffle=True, random_state=OUTER_SEED)
    outer_splits = list(outer_cv.split(np.zeros(len(y)), y))
    weights_grid = simplex_grid(len(MODELS), GRID_STEP)
    model_names = ["xgboost", "lightgbm", "catboost"]
    fold_results, validation_frames, level1_train_files = [], [], []
    outer_baseline_oof = np.full(len(y), np.nan, dtype=np.float32)
    outer_equal_oof = np.full(len(y), np.nan, dtype=np.float32)
    outer_grid_oof = np.full(len(y), np.nan, dtype=np.float32)
    outer_stack_oof = np.full(len(y), np.nan, dtype=np.float32)

    for outer_no, (outer_tr_idx, outer_va_idx) in enumerate(outer_splits, start=1):
        outer_started = time.perf_counter()
        y_outer = y[outer_tr_idx]
        train_frame = raw.iloc[outer_tr_idx].reset_index(drop=True)
        valid_frame = raw.iloc[outer_va_idx].reset_index(drop=True)
        xtr_df = pd.get_dummies(train_frame, columns=categorical, dtype=np.int8)
        xva_df = pd.get_dummies(valid_frame, columns=categorical, dtype=np.int8).reindex(columns=xtr_df.columns, fill_value=0)
        x_outer_train = xtr_df.to_numpy(dtype=np.float32, copy=False)
        x_outer_valid = xva_df.to_numpy(dtype=np.float32, copy=False)

        inner_cv = StratifiedKFold(INNER_FOLDS, shuffle=True, random_state=INNER_SEED_BASE + outer_no)
        inner_oof = np.full((len(outer_tr_idx), len(MODELS)), np.nan, dtype=np.float32)
        outer_valid_pred = np.zeros((len(outer_va_idx), len(MODELS)), dtype=np.float64)
        fit_seconds = {m: 0.0 for m in MODELS}
        inner_splits = list(inner_cv.split(np.zeros(len(y_outer)), y_outer))

        for inner_no, (inner_tr_idx, inner_va_idx) in enumerate(inner_splits, start=1):
            # Strict nesting assertion: neither outer validation rows nor inner-held
            # rows can enter this first-layer fit.
            if np.intersect1d(outer_tr_idx[inner_tr_idx], outer_va_idx).size:
                raise AssertionError("Outer validation leaked into first-layer training")
            for model_idx, model_name in enumerate(MODELS):
                fit_started = time.perf_counter()
                model = fit_base(model_name, x_outer_train[inner_tr_idx], y_outer[inner_tr_idx])
                fit_seconds[model_name] += time.perf_counter() - fit_started
                inner_oof[inner_va_idx, model_idx] = model.predict_proba(x_outer_train[inner_va_idx])[:, 1]
                outer_valid_pred[:, model_idx] += model.predict_proba(x_outer_valid)[:, 1] / INNER_FOLDS
                del model
            print(f"outer={outer_no}/{OUTER_FOLDS} inner={inner_no}/{INNER_FOLDS} first-layer OOF done", flush=True)
            gc.collect()

        if not np.isfinite(inner_oof).all() or not np.isfinite(outer_valid_pred).all():
            raise ValueError(f"Incomplete first-layer OOF predictions at outer fold {outer_no}")
        if np.intersect1d(outer_tr_idx, outer_va_idx).size:
            raise AssertionError("Outer train/validation overlap")

        # Level-2 model trains only on genuine inner-OOF predictions for outer-train.
        meta = LogisticRegression(C=LR_C, penalty="l2", solver="lbfgs", max_iter=500, random_state=MODEL_SEED)
        meta.fit(inner_oof, y_outer)
        p_stack = meta.predict_proba(outer_valid_pred)[:, 1]
        p_equal = outer_valid_pred.mean(axis=1)
        train_scores = []
        for w in weights_grid:
            train_scores.append(roc_auc_score(y_outer, inner_oof @ w))
        w_best = weights_grid[int(np.argmax(train_scores))]
        p_grid = outer_valid_pred @ w_best
        p_current = current_best[outer_va_idx]

        outer_baseline_oof[outer_va_idx] = p_current
        outer_equal_oof[outer_va_idx] = p_equal
        outer_grid_oof[outer_va_idx] = p_grid
        outer_stack_oof[outer_va_idx] = p_stack
        result = {
            "outer_fold": outer_no,
            "n_outer_train": len(outer_tr_idx), "n_outer_valid": len(outer_va_idx),
            "current_best_simple_oof_auc_reference": roc_auc_score(y[outer_va_idx], p_current),
            "strict_nested_equal_fusion_auc": roc_auc_score(y[outer_va_idx], p_equal),
            "strict_nested_inner_grid_simple_auc": roc_auc_score(y[outer_va_idx], p_grid),
            "strict_nested_logistic_stacking_auc": roc_auc_score(y[outer_va_idx], p_stack),
            "delta_stacking_vs_nested_grid_simple": roc_auc_score(y[outer_va_idx], p_stack) - roc_auc_score(y[outer_va_idx], p_grid),
            "delta_stacking_vs_current_best_reference": roc_auc_score(y[outer_va_idx], p_stack) - roc_auc_score(y[outer_va_idx], p_current),
            "xgb_inner_oof_auc": roc_auc_score(y_outer, inner_oof[:, 0]),
            "lgb_inner_oof_auc": roc_auc_score(y_outer, inner_oof[:, 1]),
            "cat_inner_oof_auc": roc_auc_score(y_outer, inner_oof[:, 2]),
            "xgb_lgb_inner_oof_corr": np.corrcoef(inner_oof[:, 0], inner_oof[:, 1])[0, 1],
            "grid_w_xgboost": w_best[0], "grid_w_lightgbm": w_best[1], "grid_w_catboost": w_best[2],
            "level2_C": LR_C,
            "xgb_fit_seconds": fit_seconds["xgboost"], "lgb_fit_seconds": fit_seconds["lightgbm"], "cat_fit_seconds": fit_seconds["catboost"],
            "outer_total_seconds": time.perf_counter() - outer_started,
        }
        fold_results.append(result)
        pd.DataFrame(fold_results).to_csv(OUT / "outer_fold_results_partial.csv", index=False)

        train_file = OUT / f"outer_{outer_no}_level1_train_oof.csv"
        pd.DataFrame({
            ID: sample_ids.iloc[outer_tr_idx].to_numpy(), TARGET: y_outer,
            "xgboost_oof": inner_oof[:, 0], "lightgbm_oof": inner_oof[:, 1], "catboost_oof": inner_oof[:, 2],
        }).to_csv(train_file, index=False)
        level1_train_files.append(str(train_file.name))
        validation_frames.append(pd.DataFrame({
            ID: sample_ids.iloc[outer_va_idx].to_numpy(), TARGET: y[outer_va_idx],
            "current_best_simple_oof_reference": p_current,
            "nested_xgboost": outer_valid_pred[:, 0], "nested_lightgbm": outer_valid_pred[:, 1], "nested_catboost": outer_valid_pred[:, 2],
            "nested_equal_fusion": p_equal, "nested_inner_grid_fusion": p_grid, "nested_logistic_stacking": p_stack,
        }))
        print(
            f"OUTER {outer_no}: current={result['current_best_simple_oof_auc_reference']:.6f} "
            f"nested_equal={result['strict_nested_equal_fusion_auc']:.6f} "
            f"nested_grid={result['strict_nested_inner_grid_simple_auc']:.6f} "
            f"stack={result['strict_nested_logistic_stacking_auc']:.6f} "
            f"weights={w_best.round(1).tolist()} time={result['outer_total_seconds']:.1f}s",
            flush=True,
        )
        gc.collect()

    if any(not np.isfinite(a).all() for a in [outer_baseline_oof, outer_equal_oof, outer_grid_oof, outer_stack_oof]):
        raise ValueError("Outer OOF predictions incomplete")
    fold_df = pd.DataFrame(fold_results)
    fold_df.to_csv(OUT / "outer_fold_results.csv", index=False)
    pd.concat(validation_frames, ignore_index=True).to_csv(OUT / "outer_validation_predictions.csv", index=False)
    comparisons = [
        ("current_best_simple_oof_reference", "current_best_simple_oof_auc_reference"),
        ("strict_nested_equal_fusion", "strict_nested_equal_fusion_auc"),
        ("strict_nested_inner_grid_simple", "strict_nested_inner_grid_simple_auc"),
        ("strict_nested_logistic_stacking", "strict_nested_logistic_stacking_auc"),
    ]
    summary_rows = []
    for name, col in comparisons:
        vals = fold_df[col].to_numpy()
        summary_rows.append({
            "method": name, "mean_fold_auc": vals.mean(),
            "std_fold_auc_population": vals.std(ddof=0), "std_fold_auc_sample": vals.std(ddof=1),
            "fold_wins_vs_current_reference": int(np.sum(vals > fold_df["current_best_simple_oof_auc_reference"].to_numpy())),
            "fold_aucs": ";".join(f"{v:.9f}" for v in vals),
        })
    pd.DataFrame(summary_rows).to_csv(OUT / "comparison_summary.csv", index=False)
    np.save(OUT / "current_best_simple_outer_reference_oof.npy", outer_baseline_oof)
    np.save(OUT / "strict_nested_equal_fusion_oof.npy", outer_equal_oof)
    np.save(OUT / "strict_nested_inner_grid_fusion_oof.npy", outer_grid_oof)
    np.save(OUT / "strict_nested_logistic_stacking_oof.npy", outer_stack_oof)
    config["saved_strict_inner_oof_files"] = level1_train_files
    config["total_wall_seconds"] = time.perf_counter() - started_all
    (OUT / "experiment_config.json").write_text(json.dumps(config, indent=2, ensure_ascii=False), encoding="utf-8")
    print("\nSUMMARY\n", pd.DataFrame(summary_rows).to_string(index=False), flush=True)
    print("total wall seconds", config["total_wall_seconds"], flush=True)


if __name__ == "__main__":
    main()
